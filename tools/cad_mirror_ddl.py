#!/usr/bin/env python3
"""Generate the cad_mirror DDL and column catalog from the CAD structure workbook.

Development tool, not delivered (CLAUDE.md section 3: tools/ is out of the no-CJK scope).

  python3 tools/cad_mirror_ddl.py            # writes contracts/cad_mirror_catalog.csv, prints DDL to stdout
  python3 tools/cad_mirror_ddl.py > /tmp/cad_mirror.sql

Rules (CAD Mirror Database Specification v0.5, DD-90):
  - one table per sheet of "3rd API/Bill同步CAD表数据结构.xlsx", all columns, nothing added
    except mirror_inserted_at / mirror_updated_at (trigger-maintained, DD-90)
  - table name  = Table Lists "Proposed Table name", lower case; column name = translated field, lower case
  - primary key = the column with Source Index 1 (DS 2026-10-26: first field of every table is the key)
  - types are mapped wide (text / timestamp / bigint / numeric); tightening happens in staging
  - Chinese descriptions go to the catalog CSV, not into the SQL (check_no_cjk)
"""
import csv, re, sys
from pathlib import Path
import openpyxl

BASE = Path(__file__).resolve().parent.parent
XLSX = BASE / "3rd API" / "Bill同步CAD表数据结构.xlsx"
CATALOG = BASE / "contracts" / "cad_mirror_catalog.csv"

def pg_type(t):
    t0 = (t or "").strip().lower()
    base = re.sub(r"\(.*", "", t0)
    if base in ("nvarchar", "varchar", "char", "nchar", "text", "ntext", "uniqueidentifier", "xml"):
        return "text"
    if base in ("datetime", "datetime2", "smalldatetime", "timestamp"):
        return "timestamp"
    if base == "date":
        return "date"
    if base == "time":
        return "time"
    if base in ("bigint", "int", "integer", "smallint", "tinyint"):
        return "bigint"
    if base == "bit":
        return "boolean"
    if base in ("decimal", "numeric", "money", "smallmoney", "float", "real", "double"):
        return "numeric"
    if base in ("varbinary", "binary", "image"):
        return "bytea"
    return "text  -- TODO unmapped source type: %s" % t0

def norm_sheet(n):
    return re.sub(r"[（(].*", "", n).strip()

def main():
    wb = openpyxl.load_workbook(XLSX, read_only=True)
    tl = {}
    for r in wb["Table Lists"].iter_rows(min_row=2, values_only=True):
        if r[1]:
            tl[norm_sheet(r[1])] = r[2]
    out = []
    cat = []
    pks = []
    w = out.append
    w("-- cad_mirror: CAD data views mirrored by DS (DD-90). Generated by tools/cad_mirror_ddl.py; do not edit by hand.")
    w("-- Source: 3rd API/Bill同步CAD表数据结构.xlsx (74 tables). Types mapped wide on purpose; tighten in staging.")
    w("CREATE SCHEMA IF NOT EXISTS cad;")
    w("CREATE SCHEMA IF NOT EXISTS cad_meta;")
    w("")
    w("CREATE OR REPLACE FUNCTION cad.set_mirror_ts() RETURNS trigger LANGUAGE plpgsql AS $$")
    w("BEGIN")
    w("  IF TG_OP = 'INSERT' THEN NEW.mirror_inserted_at := clock_timestamp(); END IF;")
    w("  NEW.mirror_updated_at := clock_timestamp();")
    w("  RETURN NEW;")
    w("END $$;")
    w("")
    for sheet in wb.sheetnames:
        if sheet == "Table Lists":
            continue
        src = norm_sheet(sheet)
        eng = tl.get(src)
        if not eng:
            print("no Table Lists entry for", sheet, file=sys.stderr); continue
        tname = eng.lower()
        rows = [r for r in wb[sheet].iter_rows(values_only=True)]
        cols = []
        seen = set()
        for r in rows[1:]:
            # the structure block ends where the value block starts (a header row of field names)
            if cols and r and isinstance(r[0], str) and not isinstance(r[0], int):
                break
            if not r or not isinstance(r[0], int):
                continue
            idx, field, trans, typ, desc = r[0], r[1], r[2], r[3], (r[4] or "")
            cname = (trans or field or "").strip().lower()
            cname = re.sub(r"[^a-z0-9_]", "_", cname)
            if not cname:
                continue
            if cname in seen:
                cname = cname + "_" + str(idx)
            seen.add(cname)
            cols.append((idx, field, cname, typ, desc))
            cat.append([src, tname, idx, field, cname, typ, pg_type(typ).split("  --")[0], str(desc).replace("\n", " ")])
        if not cols:
            print("no columns parsed for", sheet, file=sys.stderr); continue
        pk = [c for c in cols if c[0] == 1][0]
        pks.append((src, tname, pk[1], pk[2], pk[4].replace("\n", " ")))
        w("CREATE TABLE cad.%s (" % tname)
        for idx, field, cname, typ, desc in cols:
            w("    %-40s %s," % (cname, pg_type(typ)))
        w("    mirror_inserted_at timestamptz NOT NULL DEFAULT clock_timestamp(),")
        w("    mirror_updated_at  timestamptz NOT NULL DEFAULT clock_timestamp(),")
        w("    PRIMARY KEY (%s)" % pk[2])
        w(");")
        w("CREATE INDEX ix_%s_mirror_upd ON cad.%s USING brin (mirror_updated_at);" % (tname[:50], tname))
        w("CREATE TRIGGER trg_%s_mirror_ts BEFORE INSERT OR UPDATE ON cad.%s FOR EACH ROW EXECUTE FUNCTION cad.set_mirror_ts();" % (tname[:50], tname))
        w("")
    w("-- heartbeat and reconciliation tables (spec section 5)")
    w("CREATE TABLE cad_meta.sync_heartbeat (")
    w("    sync_id          bigint PRIMARY KEY,")
    w("    started_at       timestamp NOT NULL,")
    w("    finished_at      timestamp NOT NULL,")
    w("    source_watermark timestamp,")
    w("    table_counts     jsonb,")
    w("    status           text NOT NULL CHECK (status IN ('ok','partial','failed')),")
    w("    message          text,")
    w("    received_at      timestamptz NOT NULL DEFAULT clock_timestamp()")
    w(");")
    w("CREATE TABLE cad_meta.source_daily_count (")
    w("    business_date    date NOT NULL,")
    w("    table_name       text NOT NULL,")
    w("    row_count        bigint NOT NULL,")
    w("    reported_at      timestamp NOT NULL,")
    w("    received_at      timestamptz NOT NULL DEFAULT clock_timestamp(),")
    w("    PRIMARY KEY (business_date, table_name)")
    w(");")
    w("")
    w("-- ownership and the DS writer role (LD-07 2.1): run as cad_mirror_owner; grants only, no DDL for the writer")
    w("GRANT CONNECT ON DATABASE cad_mirror TO cad_mirror_writer;")
    w("GRANT USAGE ON SCHEMA cad, cad_meta TO cad_mirror_writer;")
    w("GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA cad TO cad_mirror_writer;")
    w("GRANT INSERT ON ALL TABLES IN SCHEMA cad_meta TO cad_mirror_writer;")
    w("GRANT USAGE ON SCHEMA cad, cad_meta TO oss911_ingest;")
    w("GRANT SELECT ON ALL TABLES IN SCHEMA cad, cad_meta TO oss911_ingest;")
    with open(CATALOG, "w", newline="", encoding="utf-8") as f:
        cw = csv.writer(f)
        cw.writerow(["source_table", "mirror_table", "source_index", "source_field", "mirror_column", "source_type", "mirror_type", "description"])
        cw.writerows(cat)
    print("\n".join(out))
    print("-- primary keys (first column per table, DS 2026-10-26):", file=sys.stderr)
    for p in pks:
        print("--   %-22s %-40s %-12s -> %-28s %s" % p, file=sys.stderr)
    print("-- tables: %d, columns: %d, catalog: %s" % (len(pks), len(cat), CATALOG), file=sys.stderr)

if __name__ == "__main__":
    main()
