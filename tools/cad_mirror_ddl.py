#!/usr/bin/env python3
"""Generate the cad_mirror DDL and column catalog from the CAD structure workbook.

Development tool, not delivered (CLAUDE.md section 3: tools/ is out of the no-CJK scope).

  python3 tools/cad_mirror_ddl.py > ddl/cad_mirror/changes/0001_mirror_tables.sql
      # writes contracts/cad_mirror_catalog.csv, prints the structural change to stdout

Rules (CAD Mirror Database Specification v0.5, DD-90):
  - one table per sheet of "3rd API/Bill同步CAD表数据结构.xlsx", all columns, nothing added
    except mirror_inserted_at / mirror_updated_at (trigger-maintained, DD-90)
  - table name  = Table Lists "Proposed Table name", lower case; column name = translated field, lower case
  - primary key = the column with Source Index 1 (DS 2026-10-26: first field of every table is the key)
  - types are mapped wide (text / timestamp / bigint / numeric); tightening happens in staging
  - Chinese descriptions go to the catalog CSV, not into the SQL (check_no_cjk)
  - column names never need quoting: a translated name that is a PostgreSQL reserved word is renamed (RENAMES),
    and generation fails if one is left -- quoted names would have to be quoted in every statement, ours and DS's,
    for eight years

2026-10-26, development side (agreed with Gavin): reserved-word renames (21 columns; t_dispatchplan.yxj was
mistranslated as "order", it is the priority); no IF NOT EXISTS (the change executor decides what runs, DD-73);
the trigger keeps mirror_inserted_at, ignores whatever the writer puts into the two mirror columns, and turns an
identical re-write into a no-op (no new row version, no new timestamp -- DD-78); B-tree, not BRIN, on
mirror_updated_at (rows are updated in place by the UPSERT, DD-78); default privileges for tables added later;
database-level CONNECT is granted by infra/playbooks/41-cad-mirror.yml, not here.
"""
import csv, re, sys
from pathlib import Path
import openpyxl

BASE = Path(__file__).resolve().parent.parent
XLSX = BASE / "3rd API" / "Bill同步CAD表数据结构.xlsx"
CATALOG = BASE / "contracts" / "cad_mirror_catalog.csv"

# PostgreSQL 16 keywords that cannot be column names unquoted: pg_get_keywords() catcode R and T
RESERVED = set("""
all analyse analyze and any array as asc asymmetric authorization binary both case cast check collate
collation column concurrently constraint create cross current_catalog current_date current_role current_schema
current_time current_timestamp current_user default deferrable desc distinct do else end except false fetch
for foreign freeze from full grant group having ilike in initially inner intersect into is isnull join lateral
leading left like limit localtime localtimestamp natural not notnull null offset on only or order outer
overlaps placing primary references returning right select session_user similar some symmetric system_user
table tablesample then to trailing true union unique user using variadic verbose when where window with
""".split())

# Translated names that need another name. Keyed by (mirror table, source field) for a specific fix, or by the
# translated name alone for a rename that applies everywhere.
RENAMES_BY_FIELD = {
    ("t_dispatchplan", "yxj"): "priority",          # yxj = priority; the structure workbook translates it "order"
}
RENAMES = {
    "order": "sort_order",                          # px / xh: sort order, sequence number
    "primary": "is_primary",                        # sfsy: whether it is the primary one
    "collation": "sort_rule",                       # pxgz: sorting rule
}

def pg_type(t):
    t0 = (t or "").strip().lower()
    base = re.sub(r"\(.*", "", t0)
    if base in ("nvarchar", "varchar", "char", "nchar", "text", "ntext", "uniqueidentifier", "xml"):
        return "text"
    if base in ("datetime", "datetime2", "smalldatetime", "timestamp"):
        return "timestamp"
    if base == "date":
        return "date"
    if base == "time":
        return "time"
    if base in ("bigint", "int", "integer", "smallint", "tinyint"):
        return "bigint"
    if base == "bit":
        return "boolean"
    if base in ("decimal", "numeric", "money", "smallmoney", "float", "real", "double"):
        return "numeric"
    if base in ("varbinary", "binary", "image"):
        return "bytea"
    return "text  -- TODO unmapped source type: %s" % t0

def norm_sheet(n):
    return re.sub(r"[（(].*", "", n).strip()

def main():
    wb = openpyxl.load_workbook(XLSX, read_only=True)
    tl = {}
    for r in wb["Table Lists"].iter_rows(min_row=2, values_only=True):
        if r[1]:
            tl[norm_sheet(r[1])] = r[2]
    out = []
    cat = []
    pks = []
    w = out.append
    w("-- =====================================================================")
    w("-- cad_mirror  Structural change 0001  The CAD views mirrored by DS (DD-90 · CAD mirror specification v0.5)")
    w("-- Generated by tools/cad_mirror_ddl.py from the CAD structure workbook in 3rd API/; do not edit by hand.")
    w("-- Every table of the workbook, all columns. Types are mapped wide on purpose (a write must never fail on a")
    w("-- type); staging tightens them.")
    w("-- Run as cad_mirror_owner (run_as: owner); everything created here belongs to it.")
    w("-- =====================================================================")
    w("CREATE SCHEMA cad;")
    w("CREATE SCHEMA cad_meta;")
    w("")
    w("-- The two mirror columns are ours, maintained by this trigger whatever the writer sends (DD-90):")
    w("--   mirror_inserted_at  set once, on INSERT")
    w("--   mirror_updated_at   the watermark column: moves only when the row's content really changed")
    w("-- An UPSERT that re-writes a row unchanged returns NULL here, so no new row version is written and the")
    w("-- watermark does not move: a re-sent day or a full re-load by DS creates no false changes (DD-78).")
    w("-- clock_timestamp() is not the commit time; the ingestion window is fenced by the heartbeat (DD-90).")
    w("CREATE FUNCTION cad.set_mirror_ts() RETURNS trigger LANGUAGE plpgsql")
    w("SET search_path = pg_catalog, pg_temp AS $$")
    w("BEGIN")
    w("    IF TG_OP = 'INSERT' THEN")
    w("        NEW.mirror_inserted_at := clock_timestamp();")
    w("        NEW.mirror_updated_at  := NEW.mirror_inserted_at;")
    w("        RETURN NEW;")
    w("    END IF;")
    w("    NEW.mirror_inserted_at := OLD.mirror_inserted_at;")
    w("    NEW.mirror_updated_at  := OLD.mirror_updated_at;")
    w("    IF NEW IS NOT DISTINCT FROM OLD THEN")
    w("        RETURN NULL;")
    w("    END IF;")
    w("    NEW.mirror_updated_at := clock_timestamp();")
    w("    RETURN NEW;")
    w("END $$;")
    w("")
    for sheet in wb.sheetnames:
        if sheet == "Table Lists":
            continue
        src = norm_sheet(sheet)
        eng = tl.get(src)
        if not eng:
            print("no Table Lists entry for", sheet, file=sys.stderr); continue
        tname = eng.lower()
        rows = [r for r in wb[sheet].iter_rows(values_only=True)]
        cols = []
        seen = set()
        for r in rows[1:]:
            # the structure block ends where the value block starts (a header row of field names)
            if cols and r and isinstance(r[0], str) and not isinstance(r[0], int):
                break
            if not r or not isinstance(r[0], int):
                continue
            idx, field, trans, typ, desc = r[0], r[1], r[2], r[3], (r[4] or "")
            cname = (trans or field or "").strip().lower()
            cname = re.sub(r"[^a-z0-9_]", "_", cname)
            if not cname:
                continue
            cname = RENAMES_BY_FIELD.get((tname, field), RENAMES.get(cname, cname))
            if cname in RESERVED:
                sys.exit("%s.%s: column name %r is a reserved word; add it to RENAMES" % (tname, field, cname))
            if cname in seen:
                cname = cname + "_" + str(idx)
            seen.add(cname)
            cols.append((idx, field, cname, typ, desc))
            cat.append([src, tname, idx, field, cname, typ, pg_type(typ).split("  --")[0], str(desc).replace("\n", " ")])
        if not cols:
            print("no columns parsed for", sheet, file=sys.stderr); continue
        pk = [c for c in cols if c[0] == 1][0]
        pks.append((src, tname, pk[1], pk[2], pk[4].replace("\n", " ")))
        w("CREATE TABLE cad.%s (" % tname)
        for idx, field, cname, typ, desc in cols:
            w("    %-40s %s," % (cname, pg_type(typ)))
        w("    mirror_inserted_at timestamptz NOT NULL DEFAULT clock_timestamp(),")
        w("    mirror_updated_at  timestamptz NOT NULL DEFAULT clock_timestamp(),")
        w("    PRIMARY KEY (%s)" % pk[2])
        w(");")
        w("CREATE INDEX ix_%s_mirror_upd ON cad.%s (mirror_updated_at);" % (tname[:50], tname))
        w("CREATE TRIGGER trg_%s_mirror_ts BEFORE INSERT OR UPDATE ON cad.%s FOR EACH ROW EXECUTE FUNCTION cad.set_mirror_ts();" % (tname[:50], tname))
        w("")
    w("-- heartbeat and reconciliation tables (spec section 5)")
    w("CREATE TABLE cad_meta.sync_heartbeat (")
    w("    sync_id          bigint PRIMARY KEY,")
    w("    started_at       timestamp NOT NULL,")
    w("    finished_at      timestamp NOT NULL,")
    w("    source_watermark timestamp,")
    w("    table_counts     jsonb,")
    w("    status           text NOT NULL CHECK (status IN ('ok','partial','failed')),")
    w("    message          text,")
    w("    received_at      timestamptz NOT NULL DEFAULT clock_timestamp()")
    w(");")
    w("CREATE TABLE cad_meta.source_daily_count (")
    w("    business_date    date NOT NULL,")
    w("    table_name       text NOT NULL,")
    w("    row_count        bigint NOT NULL,")
    w("    reported_at      timestamp NOT NULL,")
    w("    received_at      timestamptz NOT NULL DEFAULT clock_timestamp(),")
    w("    PRIMARY KEY (business_date, table_name)")
    w(");")
    w("")
    w("-- Privileges (LD-07 2.1). The DS writer: read, insert and update the mirror, insert heartbeat and counts; no")
    w("-- CREATE, DELETE, TRUNCATE, TRIGGER, REFERENCES. Our ingestion: read only. CONNECT is granted per database by")
    w("-- 41-cad-mirror.yml. Default privileges cover tables a later change adds.")
    w("GRANT USAGE ON SCHEMA cad, cad_meta TO cad_mirror_writer, oss911_ingest;")
    w("GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA cad TO cad_mirror_writer;")
    w("GRANT INSERT ON ALL TABLES IN SCHEMA cad_meta TO cad_mirror_writer;")
    w("GRANT SELECT ON ALL TABLES IN SCHEMA cad, cad_meta TO oss911_ingest;")
    w("ALTER DEFAULT PRIVILEGES FOR ROLE cad_mirror_owner IN SCHEMA cad GRANT SELECT, INSERT, UPDATE ON TABLES TO cad_mirror_writer;")
    w("ALTER DEFAULT PRIVILEGES FOR ROLE cad_mirror_owner IN SCHEMA cad_meta GRANT INSERT ON TABLES TO cad_mirror_writer;")
    w("ALTER DEFAULT PRIVILEGES FOR ROLE cad_mirror_owner IN SCHEMA cad, cad_meta GRANT SELECT ON TABLES TO oss911_ingest;")
    w("REVOKE EXECUTE ON FUNCTION cad.set_mirror_ts() FROM PUBLIC;")
    with open(CATALOG, "w", newline="", encoding="utf-8") as f:
        cw = csv.writer(f)
        cw.writerow(["source_table", "mirror_table", "source_index", "source_field", "mirror_column", "source_type", "mirror_type", "description"])
        cw.writerows(cat)
    print("\n".join(out))
    print("-- primary keys (first column per table, DS 2026-10-26):", file=sys.stderr)
    for p in pks:
        print("--   %-22s %-40s %-12s -> %-28s %s" % p, file=sys.stderr)
    print("-- tables: %d, columns: %d, catalog: %s" % (len(pks), len(cat), CATALOG), file=sys.stderr)

if __name__ == "__main__":
    main()
